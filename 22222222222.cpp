#include <iostream>

int main()
{
    setlocale(LC_ALL, "Russian");
    long long totalSeconds;

    std::cout << "Введите количество секунд: ";
    std::cin >> totalSeconds;

    // Проверка на отрицательное значение
    if (totalSeconds < 0) {
        std::cout << "Ошибка: количество секунд не может быть отрицательным." << std::endl;
        return 1; // завершаем программу с кодом ошибки
    }

    // Вычисляем полные часы, минуты и секунды
    long long hours = totalSeconds / 3600;            // 1 час = 3600 секунд
    long long minutes = (totalSeconds % 3600) / 60;     // остаток от часов делим на 60
    long long seconds = totalSeconds % 60;              // остаток от минут

    std::cout << "Результат: "
        << hours << " ч "
        << minutes << " мин "
        << seconds << " сек" << std::endl;

    return 0;
}

